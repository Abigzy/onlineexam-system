"""个性化推荐模块常量。

个性化推荐与学情分析一样，是一个**纯读模型**：它不产生任何新的判分结果、
不建新表，只把「模块五的判分结果」+「模块六的知识点掌握度」两样东西
重新组合成一份「今天该练哪几道题」的清单。

这里定义四类东西：

1. **推荐规模** —— 每日练习默认几道题、一次最多几道。
   太少起不到练习作用，太多学生会直接关掉页面。
2. **匹配度权重** —— 一道题凭什么排在前面？两个信号：
   ①「内容分」：它考的知识点有多薄弱、难度是否贴合学生当前水平；
   ②「协同证据」：做错同类题的其他同学，是不是也在这道题上翻车。
   权重要写在一处，否则同一条推荐在接口和页面上会算出两个匹配度。
3. **难度目标** —— 提示词里写着「难度以略高于当前水平为宜，避免过难打击信心」。
   「当前水平」由整体正确率推算，「略高」是给薄弱知识点的题留出的余量。
4. **协同过滤门槛** —— 两道题只有一两个共同作答者时，「相似」完全是巧合。
   样本不足就判相似度为 0，让推荐自动退化为纯内容推荐（宁可少推，不可乱推）。
"""

from apps.common.constants import Difficulty

# ==================================================================
# 推荐规模
# ==================================================================
# 每日练习默认推荐题数
DAILY_DEFAULT_SIZE = 6
# 一次最多推荐多少道（页面上「换一批」也不会一次给太多）
DAILY_MAX_SIZE = 20

# ==================================================================
# 匹配度权重
# ==================================================================
# 内容分内部：知识点薄弱度占大头，难度适配度占小头
# （「考的是不是你的弱项」比「难度合不合适」更重要）
KP_WEIGHT = 0.65
DIFFICULTY_WEIGHT = 0.35

# 「证据充分度」：一个知识点作答达到这个题数，薄弱结论才算证据充分。
# 为什么要这一项：正确率 0% 是饱和的——做过 12 题全错和做过 2 题全错，
# 都是 0%，但前者是「确实不会」，后者可能只是这两道题刚好没复习到。
# 把它折进薄弱度里（而非另设一项权重），薄弱度就自然有了区分度，
# 排序也变成「证据充分且确实薄弱的知识点优先」。
# 取值 8 与 MIN_SAMPLES_FOR_WEAKNESS(2) 分工不同：2 是「够不够格叫薄弱」，
# 8 是「这个薄弱结论有多少证据」。
EVIDENCE_FULL_SAMPLE = 8

# 同一知识点在一次推荐里最多出现几道题。
# 提示词里写着「同一知识点不要连续堆叠太多题」——堆五道二叉树，
# 学生做到第三道就烦了，也测不出迁移能力。
MAX_PER_KNOWLEDGE_POINT = 2

# 协同过滤只是一个**加成**，不参与基础分：
#   match = 内容分 × (1 + CF_BONUS × 协同分)
# 这样设计的原因：协同过滤依赖「别人的作答」，冷启动阶段（只有你一个学生
# 或刚从题库导入）完全算不出相似度。如果把它做成加权平均，一旦 CF 不可用，
# 所有题的匹配度都会被拉低一截，页面上的百分比会在两种场景间跳来跳去。
# 做成乘数后，CF 不可用就等价于「没有额外证据」，分数依然可比。
CF_BONUS = 0.30

# ==================================================================
# 难度目标
# ==================================================================
# 目标难度 = 1 + round(正确率 × 3)，再夹到 1..4：
#   正确率 0%   → 难度 1（简单，先建立信心）
#   正确率 50%  → 难度 3（中等偏上，略高于当前水平）
#   正确率 100% → 难度 4（挑战）
# 无任何作答数据（正确率未知）时退回「中等」，不猜。
DEFAULT_TARGET_DIFFICULTY = Difficulty.MEDIUM
# 难度总共 1..4 四档，任意两档之间差值的上界（用于把难度差折算成 0~1 的适配度）
DIFFICULTY_SPAN = 3

# ==================================================================
# 协同过滤
# ==================================================================
# 两道题至少要有几个共同作答的学生，余弦相似度才算数
CF_MIN_COMMON_STUDENTS = 2
# 参与相似度计算的题目上限（按作答量取前 N 个）：题库上千道题时防止 O(n²) 爆炸
CF_MAX_ITEMS = 400
# 候选池上限：薄弱知识点可能覆盖几百道题，取匹配度最高的这一批就够了
CANDIDATE_POOL_MAX = 400

# ==================================================================
# AI 推荐理由
# ==================================================================
# 喂给大模型的候选题目上限——太多会把提示词撑爆，也会让「推荐」变成「乱选」
AI_MAX_CANDIDATES = 30
# AI 推荐理由的缓存有效期（小时）：同一份推荐集在有效期内不重复调用大模型
AI_REASON_TTL_HOURS = 24

